const makeUnlock = (
  items: Partial<Record<ServiceUnlockItem['service'], { status: ServiceUnlockItem['status']; detail: string }>>
): ServiceUnlockItem[] => {
  const order: { service: ServiceUnlockItem['service']; category: 'ai' | 'streaming' }[] = [
    { service: 'ChatGPT', category: 'ai' },
    { service: 'Claude', category: 'ai' },
    { service: 'Gemini', category: 'ai' },
    { service: 'Netflix', category: 'streaming' },
    { service: 'Disney+', category: 'streaming' },
    { service: 'YouTube', category: 'streaming' },
    { service: 'HBO Max', category: 'streaming' },
    { service: 'TikTok', category: 'streaming' },
    { service: 'Spotify', category: 'streaming' },
  ];
  return order.map(({ service, category }) => ({
    service,
    category,
    status: items[service]?.status ?? 'untested',
    detail: items[service]?.detail ?? '暂无独立逐项实测数据（待核实）',
  }));
};

